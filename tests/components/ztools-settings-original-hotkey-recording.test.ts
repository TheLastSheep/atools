import { afterEach, describe, expect, it, vi } from 'vitest'
import { originalGeneralHotkeyHandler, recordingComponentFixture } from './ztoolsSettingsHotkeyRecordingComponentFixture'

let fixture: ReturnType<typeof recordingComponentFixture> | undefined
afterEach(() => fixture?.dispose())
const recording = (root: HTMLElement) => root.querySelector('.hotkey-input')!.classList.contains('recording')
const click = (root: HTMLElement) => (root.querySelector('.hotkey-input') as HTMLElement).click()

describe('pinned original HotkeyInput recording lifecycle', () => {
  it('stops the Native lease when a normal DOM combination is confirmed', async () => {
    fixture = recordingComponentFixture()
    const changed = vi.fn(), item = fixture.mount(changed)
    click(item.root); await fixture.tick()
    expect(recording(item.root)).toBe(true)
    expect(fixture.activeDomListeners.size).toBe(1)
    fixture.key('keydown', 'k', 'KeyK', { metaKey: true }); fixture.key('keyup', 'k', 'KeyK', { metaKey: true })
    await fixture.tick()
    expect(changed).toHaveBeenCalledWith('Command+K')
    expect(recording(item.root)).toBe(false)
    expect(fixture.calls).toContainEqual({ operation: 'stopHotkeyRecording', generation: 1 })
  })
  it('continues DOM fallback after native start fails', async () => {
    fixture = recordingComponentFixture({ failStart: true })
    const changed = vi.fn(), item = fixture.mount(changed)
    click(item.root); await fixture.tick()
    expect(fixture.activeDomListeners.size).toBe(1)
    fixture.key('keydown', 'F6', 'F6'); fixture.key('keyup', 'F6', 'F6')
    await fixture.tick()
    expect(changed).toHaveBeenCalledWith('F6')
    expect(recording(item.root)).toBe(false)
  })
  it('never installs DOM listeners after a pending start was cancelled or unmounted', async () => {
    fixture = recordingComponentFixture({ holdStart: true })
    const changed = vi.fn(), first = fixture.mount(changed)
    click(first.root); first.vm.stopRecording(); fixture.release(); await fixture.tick()
    fixture.key('keydown', 'k', 'KeyK', { metaKey: true }); fixture.key('keyup', 'k', 'KeyK', { metaKey: true })
    expect(changed).not.toHaveBeenCalled()
    expect(fixture.activeDomListeners.size).toBe(0)
    const second = fixture.mount(changed)
    click(second.root); second.app.unmount(); fixture.release(); await fixture.tick()
    fixture.key('keydown', 'F7', 'F7'); fixture.key('keyup', 'F7', 'F7')
    expect(changed).not.toHaveBeenCalled()
    expect(fixture.activeDomListeners.size).toBe(0)
    expect(fixture.calls.filter(call => call.operation === 'stopHotkeyRecording').map(call => call.generation)).toContain(2)
  })
  it('consumes early native input once and ignores previous-generation events on rerecording', async () => {
    fixture = recordingComponentFixture({ holdStart: true })
    const changed = vi.fn(), item = fixture.mount(changed)
    click(item.root); fixture.deliver(1); fixture.release(); await fixture.tick()
    expect(changed).toHaveBeenCalledTimes(1)
    expect(recording(item.root)).toBe(false)
    fixture.key('keydown', 'F8', 'F8'); fixture.key('keyup', 'F8', 'F8')
    expect(changed).toHaveBeenCalledTimes(1)
    click(item.root); fixture.release(); await fixture.tick()
    fixture.deliver(1); expect(recording(item.root)).toBe(true)
    fixture.deliver(2); fixture.deliver(2); await fixture.tick()
    expect(changed).toHaveBeenCalledTimes(2)
    expect(recording(item.root)).toBe(false)
  })
  it('shows timeout as stopped and removes route recording listeners', async () => {
    fixture = recordingComponentFixture()
    const changed = vi.fn(), item = fixture.mount(changed)
    click(item.root); await fixture.tick()
    fixture.deliver(1, { status: 'stopped', reason: 'timeout', shortcut: undefined })
    await fixture.tick()
    expect(recording(item.root)).toBe(false)
    click(item.root); await fixture.tick()
    window.dispatchEvent(new Event('hashchange')); await fixture.tick()
    expect(recording(item.root)).toBe(false)
    fixture.key('keydown', 'F9', 'F9'); fixture.key('keyup', 'F9', 'F9')
    expect(changed).not.toHaveBeenCalled()
  })
  it('hands ownership to the second widget and old unmount cannot stop or confirm the new widget', async () => {
    fixture = recordingComponentFixture()
    const firstChanged = vi.fn(), secondChanged = vi.fn()
    const first = fixture.mount(firstChanged), second = fixture.mount(secondChanged)
    click(first.root); await fixture.tick()
    click(second.root); await fixture.tick()
    expect(recording(first.root)).toBe(false); expect(recording(second.root)).toBe(true)
    const beforeUnmount = fixture.calls.length
    first.app.unmount(); await fixture.tick()
    expect(fixture.calls).toHaveLength(beforeUnmount)
    fixture.deliver(1); expect(secondChanged).not.toHaveBeenCalled()
    fixture.deliver(2); await fixture.tick()
    expect(firstChanged).not.toHaveBeenCalled()
    expect(secondChanged).toHaveBeenCalledTimes(1)
    expect(recording(second.root)).toBe(false)
  })

  it('native one-shot confirms through the original General handler and existing CAS save, with conflict rollback', async () => {
    fixture = recordingComponentFixture()
    const original = originalGeneralHotkeyHandler(fixture.general.internal, fixture.runtime)
    const item = fixture.mount(original.change)
    click(item.root); await fixture.tick(); fixture.deliver(1)
    await vi.waitFor(() => expect(fixture!.general.calls.filter(call => call.operation === 'patchGeneral')).toHaveLength(1))
    expect(original.hotkey.value).toBe('Option+Space')
    expect(await fixture.general.internal.getCurrentShortcut()).toBe('Option+Space')
    expect(original.errors).toEqual([])
    fixture.general.rejectShortcut('Option+Space')
    click(item.root); await fixture.tick(); fixture.deliver(2)
    await vi.waitFor(() => expect(original.errors).toHaveLength(1))
    expect(original.hotkey.value).toBe('Option+Space')
    expect(fixture.general.calls.filter(call => call.operation === 'patchGeneral')).toHaveLength(2)
  })
  it('a rejected native candidate restores the previous confirmed key in the original General flow', async () => {
    fixture = recordingComponentFixture()
    fixture.general.rejectShortcut('Option+Space')
    const original = originalGeneralHotkeyHandler(fixture.general.internal, fixture.runtime)
    const item = fixture.mount(original.change)
    click(item.root); await fixture.tick(); fixture.deliver(1)
    await vi.waitFor(() => expect(original.errors).toHaveLength(1))
    expect(original.hotkey.value).toBe('Option+Z')
    expect(await fixture.general.internal.getCurrentShortcut()).toBe('Option+Z')
  })

  it.each([
    ['SETTINGS_HOTKEY_LISTEN_PERMISSION_REQUIRED', '双击修饰键需要输入监听权限，请在系统设置中授权后重试。'],
    ['SETTINGS_HOTKEY_DOUBLE_TAP_UNSUPPORTED', '当前系统暂不支持双击修饰键，请使用普通组合键。']
  ])('restores the original widget value after %s and allows ordinary-key fallback', async (code, message) => {
    fixture = recordingComponentFixture()
    fixture.general.failNextPatch({ code, message: 'private native detail' })
    const original = originalGeneralHotkeyHandler(fixture.general.internal, fixture.runtime)
    const item = fixture.mount(original.change)
    click(item.root); await fixture.tick()
    for (let tap = 0; tap < 2; tap++) {
      fixture.key('keydown', 'Meta', 'MetaLeft', { metaKey: true }); fixture.key('keyup', 'Meta', 'MetaLeft')
    }
    await vi.waitFor(() => expect(original.errors).toEqual([`快捷键设置失败: ${message}`]))
    expect(recording(item.root)).toBe(false)
    expect(original.hotkey.value).toBe('Option+Z')
    expect(await fixture.general.internal.getCurrentShortcut()).toBe('Option+Z')
    expect(fixture.general.calls.filter(call => call.operation === 'patchGeneral')).toHaveLength(1)
    click(item.root); await fixture.tick()
    fixture.key('keydown', 'F10', 'F10', { altKey: true }); fixture.key('keyup', 'F10', 'F10', { altKey: true })
    await vi.waitFor(async () => expect(await fixture!.general.internal.getCurrentShortcut()).toBe('Option+F10'))
    expect(original.hotkey.value).toBe('Option+F10')
    expect(fixture.general.calls.filter(call => call.operation === 'patchGeneral')).toHaveLength(2)
  })

  it('unavailable stops the visible recording, retries retained cleanup once and retries again on unmount', async () => {
    fixture = recordingComponentFixture({ failStops: 1 })
    const changed = vi.fn(), item = fixture.mount(changed)
    click(item.root); await fixture.tick()
    fixture.deliver(1, { status: 'stopped', reason: 'unavailable' }); await fixture.tick()
    expect(recording(item.root)).toBe(false)
    expect(fixture.activeDomListeners.size).toBe(0)
    expect(fixture.calls.filter(call => call.operation === 'stopHotkeyRecording')).toHaveLength(1)
    fixture.deliver(1, { status: 'stopped', reason: 'unavailable' }); await fixture.tick()
    expect(fixture.calls.filter(call => call.operation === 'stopHotkeyRecording')).toHaveLength(1)
    item.app.unmount(); await fixture.tick()
    expect(fixture.calls.filter(call => call.operation === 'stopHotkeyRecording')).toHaveLength(2)
    expect(changed).not.toHaveBeenCalled()
  })

  it('waits for a held stop ACK before emitting one original General CAS save', async () => {
    fixture = recordingComponentFixture({ holdStop: true })
    const original = originalGeneralHotkeyHandler(fixture.general.internal, fixture.runtime)
    const changed = vi.fn(original.change), item = fixture.mount(changed)
    click(item.root); await fixture.tick()
    fixture.key('keydown', 'k', 'KeyK', { metaKey: true }); fixture.key('keyup', 'k', 'KeyK', { metaKey: true })
    expect(changed).not.toHaveBeenCalled()
    expect(fixture.general.calls.filter(call => call.operation === 'patchGeneral')).toHaveLength(0)
    fixture.releaseStop(); await fixture.tick()
    await vi.waitFor(() => expect(fixture!.general.calls.filter(call => call.operation === 'patchGeneral')).toHaveLength(1))
    expect(changed).toHaveBeenCalledTimes(1)
    expect(original.hotkey.value).toBe('Command+K')
  })
  it('never saves a DOM candidate when Native stop rejects', async () => {
    fixture = recordingComponentFixture({ failStops: 1 })
    const original = originalGeneralHotkeyHandler(fixture.general.internal, fixture.runtime)
    const changed = vi.fn(original.change), item = fixture.mount(changed)
    click(item.root); await fixture.tick()
    fixture.key('keydown', 'k', 'KeyK', { metaKey: true }); fixture.key('keyup', 'k', 'KeyK', { metaKey: true })
    await fixture.tick()
    expect(changed).not.toHaveBeenCalled()
    expect(fixture.general.calls.filter(call => call.operation === 'patchGeneral')).toHaveLength(0)
    expect(original.hotkey.value).toBe('Option+Z')
  })
  it('does not save a previously confirmed DOM candidate after unmount while stop is pending', async () => {
    fixture = recordingComponentFixture({ holdStop: true })
    const changed = vi.fn(), item = fixture.mount(changed)
    click(item.root); await fixture.tick()
    fixture.key('keydown', 'F6', 'F6'); fixture.key('keyup', 'F6', 'F6')
    item.app.unmount(); fixture.releaseStop(); await fixture.tick()
    expect(changed).not.toHaveBeenCalled()
    expect(fixture.activeDomListeners.size).toBe(0)
  })

  it('a newer recording invalidates a candidate waiting for the previous stop ACK', async () => {
    fixture = recordingComponentFixture({ holdStop: true })
    const changed = vi.fn(), item = fixture.mount(changed)
    click(item.root); await fixture.tick()
    fixture.key('keydown', 'F6', 'F6'); fixture.key('keyup', 'F6', 'F6')
    click(item.root)
    expect(fixture.calls.filter(call => call.operation === 'startHotkeyRecording')).toHaveLength(1)
    fixture.releaseStop()
    await vi.waitFor(() => expect(fixture!.calls.filter(call => call.operation === 'startHotkeyRecording')).toHaveLength(2))
    await fixture.tick()
    expect(changed).not.toHaveBeenCalled()
    fixture.deliver(2); await fixture.tick()
    expect(changed).toHaveBeenCalledTimes(1)
    expect(changed).toHaveBeenCalledWith('Option+Space')
  })

  it('keeps the native lease for orphan Space keyup before the released native recording arrives', async () => {
    fixture = recordingComponentFixture()
    const changed = vi.fn(), item = fixture.mount(changed)
    click(item.root); await fixture.tick()
    fixture.key('keyup', ' ', 'Space')
    await fixture.runtime.nextTick()
    expect(recording(item.root)).toBe(true)
    expect(fixture.calls.filter(call => call.operation === 'stopHotkeyRecording')).toHaveLength(0)
    fixture.deliver(1); await fixture.tick()
    expect(changed).toHaveBeenCalledTimes(1)
    expect(changed).toHaveBeenCalledWith('Option+Space')
    expect(recording(item.root)).toBe(false)
  })

  it('still confirms Space when its ordinary DOM keydown was observed', async () => {
    fixture = recordingComponentFixture()
    const changed = vi.fn(), item = fixture.mount(changed)
    click(item.root); await fixture.tick()
    fixture.key('keydown', ' ', 'Space', { altKey: true }); fixture.key('keyup', ' ', 'Space', { altKey: true })
    await fixture.tick()
    expect(changed).toHaveBeenCalledTimes(1)
    expect(changed).toHaveBeenCalledWith('Option+Space')
  })
  it('preserves the original DOM double-modifier recording without claiming global execution support', async () => {
    fixture = recordingComponentFixture()
    const changed = vi.fn(), item = fixture.mount(changed)
    click(item.root); await fixture.tick()
    for (let tap = 0; tap < 2; tap++) {
      fixture.key('keydown', 'Meta', 'MetaLeft', { metaKey: true }); fixture.key('keyup', 'Meta', 'MetaLeft')
    }
    await fixture.tick()
    expect(changed).toHaveBeenCalledTimes(1)
    expect(changed).toHaveBeenCalledWith('Command+Command')
  })

  it('records Command+W through the original DOM after closePlugin is disabled without proving AppKit routing', async () => {
    fixture = recordingComponentFixture()
    await fixture.general.internal.dbPut('settings-general', { builtinAppShortcutsEnabled: { closePlugin: false } })
    const original = originalGeneralHotkeyHandler(fixture.general.internal, fixture.runtime)
    const item = fixture.mount(original.change)
    click(item.root); await fixture.tick()
    fixture.key('keydown', 'w', 'KeyW', { metaKey: true })
    fixture.key('keyup', 'w', 'KeyW', { metaKey: true })
    await vi.waitFor(async () => expect(await fixture!.general.internal.getCurrentShortcut()).toBe('Command+W'))
    expect(original.hotkey.value).toBe('Command+W')
    expect(recording(item.root)).toBe(false)
    expect(original.errors).toEqual([])
    expect(fixture.general.calls.filter(call => call.operation === 'patchGeneral').map(call => call.payload.changes)).toEqual([
      { builtinAppShortcutsEnabled: { closePlugin: false } }, { hotkey: 'Command+W' }
    ])
  })

})
